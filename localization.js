function regexLiteral(text) {
  return text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function englishTemplates() {
  if (translationTemplates) return translationTemplates;
  translationTemplates = Object.entries({ ...ENGLISH_TEMPLATES, ...ENGLISH_FORMATS }).map(([source, english]) => {
    const parts = source.split(SLOT_MARKER);
    const literals = parts.filter((_, index) => index % 2 === 0);
    const length = literals.join('').replace(/\s/g, '').length;
    if (length < 2 || !literals.some(part => HAN_TEXT.test(part))) return null;
    const needle = literals.reduce((longest, current) => current.length > longest.length ? current : longest, '').trim();
    const slots = parts.filter((_, index) => index % 2 === 1);
    const expression = parts.map((part, index) => index % 2 ? '(.*?)' : regexLiteral(part)).join('');
    return { pattern: new RegExp('^' + expression + '$', 'u'), english, slots, length, needle };
  }).filter(Boolean).sort((a, b) => b.length - a.length);
  return translationTemplates;
}

