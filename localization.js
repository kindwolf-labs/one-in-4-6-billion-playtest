function translateText(value) {
  if (typeof value !== 'string' || state.resolvedLang !== 'en' || !HAN_TEXT.test(value)) return value;
  const key = value.replace(/\s+/g, ' ').trim();
  let translation = translationCache.get(key);
  if (translation === undefined) {
    translation = translateEnglish(key, 0);
    if (translationCache.size >= 2500) translationCache.clear();
    translationCache.set(key, translation);
  }
  if (translation === key) return value;
  const leading = value.match(/^\s*/)[0];
  const trailing = value.match(/\s*$/)[0];
  return leading + translation + trailing;
}

function localizeTextNode(node) {
  const container = node.parentElement;
  if (!container || container.closest('script, style, textarea, [data-user-text]')) return;
  const current = node.nodeValue;
  const previous = localizedNodes.get(node);
  const source = previous && previous.output === current ? previous.source : current;
  const output = translateText(source);
  if (output !== current) node.nodeValue = output;
  if (output !== source) localizedNodes.set(node, { source, output });
  else localizedNodes.delete(node);
}

const TRANSLATED_ATTRIBUTES = ['title', 'placeholder', 'aria-label', 'alt'];
function localizeAttributes(element) {
  let remembered = localizedAttributes.get(element);
  for (const attribute of TRANSLATED_ATTRIBUTES) {
    const current = element.getAttribute(attribute);
    if (!current) continue;
    const entry = remembered?.[attribute];
    const source = entry && entry.output === current ? entry.source : current;
    const output = translateText(source);
    if (output !== current) element.setAttribute(attribute, output);
    if (output !== source) {
      remembered ||= {};
      remembered[attribute] = { source, output };
      localizedAttributes.set(element, remembered);
    } else if (remembered) delete remembered[attribute];
  }
}

